// Generates supabase/migrations/007_english_foundations.sql — ADDITIVE seed of
// the new English Foundations module (Phase 2E) into public.course_phrases.
// Migration 005 already seeded the sales lessons; this only ADDS the new
// foundation phrase ids (upsert, NO prune) so it can't touch existing rows.
// English reuses the generic 005 layer; no new tables/RPCs/grants.
//
// Run:  node scripts/gen-english-foundations-seed.mjs   (Node >= 22)

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const COURSE_ID = "english-sales";
const FOUNDATION_MODULE_ID = "m0_foundations";

const { ENGLISH_COURSE } = await import("../lib/englishCourse.ts");

const mod = ENGLISH_COURSE.modules.find((m) => m.id === FOUNDATION_MODULE_ID);
if (!mod) {
  console.error(`Module ${FOUNDATION_MODULE_ID} not found.`);
  process.exit(1);
}

const rows = [];
for (const lesson of mod.lessons) {
  for (const p of lesson.phrases) rows.push({ lesson: lesson.id, phrase: p.id });
}
if (rows.length === 0) {
  console.error("No foundation phrases found.");
  process.exit(1);
}

const lessonCount = new Set(rows.map((r) => r.lesson)).size;
const values = rows.map((r) => `  ('${COURSE_ID}', '${r.lesson}', '${r.phrase}')`).join(",\n");

const sql = `-- Phase 2E — ADDITIVE seed of the English Foundations module into
-- public.course_phrases (IDEMPOTENT). Re-runnable in the Supabase SQL Editor.
--
-- Depends on: 005_course_progress.sql (generic tables + RPCs already applied).
-- This ONLY adds the new foundation phrase ids — it does NOT prune, so the
-- existing sales-lesson seed from 005 is untouched. No new tables/RPCs/grants.
-- English stays out of the certificate flow; this is just the course-progress
-- catalog so the existing RPCs accept foundation writes.
--
-- Generated by scripts/gen-english-foundations-seed.mjs from lib/englishCourse.ts.
-- ${rows.length} English foundation phrases across ${lessonCount} lessons.

insert into public.course_phrases (course_id, lesson_id, phrase_id) values
${values}
on conflict (course_id, phrase_id) do update set
  lesson_id = excluded.lesson_id,
  updated_at = now();

-- Verify
select
  (select count(*) from public.course_phrases where course_id = '${COURSE_ID}')                       as english_phrases_total,
  (select count(*) from public.course_phrases where course_id = '${COURSE_ID}' and lesson_id like 'english_basics_%') as foundation_phrases,
  (select count(distinct lesson_id) from public.course_phrases where course_id = '${COURSE_ID}')      as english_lessons_total;
-- Expected after 005 + 007: english_phrases_total=${128 + rows.length}, foundation_phrases=${rows.length}, english_lessons_total=${16 + lessonCount}.
`;

const target = path.join(root, "supabase", "migrations", "007_english_foundations.sql");
fs.writeFileSync(target, sql, "utf8");
console.log(`✅ Wrote ${path.relative(root, target)}`);
console.log(`   foundation phrases=${rows.length} lessons=${lessonCount}`);
