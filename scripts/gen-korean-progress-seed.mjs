// Generates supabase/migrations/006_korean_course_progress.sql straight from
// lib/koreanCourse.ts, so the Korean seed can't drift from the content.
// Korean REUSES the generic course-progress tables + RPCs from migration 005;
// 006 only seeds course_phrases for course_id='korean-sales'. No new tables,
// RPCs, or grants. Korean stays OUT of Hall of Fame and has NO certificate.
//
// Run:  node scripts/gen-korean-progress-seed.mjs
// Requires Node >= 22 (TypeScript type-stripping). No app code touched.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const COURSE_ID = "korean-sales";

const { KOREAN_COURSE } = await import("../lib/koreanCourse.ts");

const rows = [];
for (const mod of KOREAN_COURSE.modules) {
  for (const lesson of mod.lessons) {
    for (const p of lesson.phrases) {
      rows.push({ lesson: lesson.id, phrase: p.id });
    }
  }
}
if (rows.length === 0) {
  console.error("No Korean phrases found — check the source format.");
  process.exit(1);
}

const lessonCount = new Set(rows.map((r) => r.lesson)).size;
const values = rows.map((r) => `  ('${COURSE_ID}', '${r.lesson}', '${r.phrase}')`).join(",\n");
const idList = rows.map((r) => `'${r.phrase}'`).join(", ");

const sql = `-- Phase 2D — seed the Korean course (course_id='${COURSE_ID}') into
-- public.course_phrases (IDEMPOTENT). Re-runnable in the Supabase SQL Editor.
--
-- Depends on: 005_course_progress.sql (the generic course-progress tables,
--   RLS, and the SECURITY DEFINER RPCs). Korean REUSES that layer verbatim —
--   this migration adds NO tables, RPCs, policies, or grants. It only registers
--   Korean phrase ids so the existing RPCs accept Korean writes.
--
-- Scope guard (unchanged by design):
--   - Korean is NOT included in the Hall of Fame / weekly leaderboard.
--   - Korean has NO certificate.
--   - Voice attempts store metadata only (result + optional score) — NO transcript.
--   - No service_role. No secrets.
--
-- Generated by scripts/gen-korean-progress-seed.mjs from lib/koreanCourse.ts.
-- ${rows.length} Korean phrases across ${lessonCount} lessons.

insert into public.course_phrases (course_id, lesson_id, phrase_id) values
${values}
on conflict (course_id, phrase_id) do update set
  lesson_id = excluded.lesson_id,
  updated_at = now();

-- Prune any Korean phrase ids no longer present in content (reference rows only).
delete from public.course_phrases
 where course_id = '${COURSE_ID}'
   and phrase_id not in (${idList});

-- Verify
select
  (select count(*) from public.course_phrases where course_id = '${COURSE_ID}')                  as korean_phrases_seeded,
  (select count(distinct lesson_id) from public.course_phrases where course_id = '${COURSE_ID}') as korean_lessons;
-- Expected: korean_phrases_seeded=${rows.length}, korean_lessons=${lessonCount}.
`;

const target = path.join(root, "supabase", "migrations", "006_korean_course_progress.sql");
fs.writeFileSync(target, sql, "utf8");
console.log(`✅ Wrote ${path.relative(root, target)}`);
console.log(`   course=${COURSE_ID} phrases=${rows.length} lessons=${lessonCount}`);
