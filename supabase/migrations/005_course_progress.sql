-- Phase 2C.2 — generic multi-course progress layer (IDEMPOTENT).
-- Re-runnable in the Supabase SQL Editor. Safe to paste again; no data loss.
-- Depends on: 001 (user_role(), touch_updated_at()) must be applied first.
--
-- WHY a NEW generic layer (not the Chinese tables):
--   The Chinese course keeps its bespoke tables (lesson_progress, voice_attempts,
--   phrase_progress) + cert/leaderboard pipeline UNTOUCHED. New courses (English
--   first) use these course-scoped tables keyed by (user_id, course_id, ...).
--   No Chinese migration, no destructive change.
--
-- What this adds:
--   - course_phrases        : reference table (course_id, lesson_id, phrase_id),
--                             seeded from lib/englishCourse.ts. RPCs validate
--                             phrase/lesson existence against THIS table.
--   - course_phrase_progress: per-user phrase "learned".
--   - course_voice_attempts : per-user English voice attempts (metadata only —
--                             NO transcript stored; privacy-preserving).
--   - course_quiz_attempts  : per-user English quiz attempts (append-only).
--   - course_lesson_progress: per-user lesson completion.
--   - FORCE RLS on all: staff = own rows only; manager = read all. No public.
--   - 4 SECURITY DEFINER RPCs (server is source of truth; direct writes revoked).
--
-- SECURITY MODEL:
--   - Tables grant SELECT only to authenticated; INSERT/UPDATE/DELETE are NOT
--     granted. All writes flow through SECURITY DEFINER RPCs that hard-set
--     user_id = auth.uid(), so a caller can only ever write their OWN rows and
--     cannot forge another user's progress.
--   - RPCs validate course_id/lesson_id/phrase_id against course_phrases, the
--     result enum, score bounds and quiz totals.
--   - No service_role. No secrets.

