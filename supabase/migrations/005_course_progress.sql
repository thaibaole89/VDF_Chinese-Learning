-- mark_course_phrase_learned: validates (course_id, phrase_id) in course_phrases
-- and that the supplied lesson matches. Upserts learned state.
create or replace function public.mark_course_phrase_learned(
  p_course_id text,
  p_lesson_id text,
  p_phrase_id text,
  p_learned   boolean default true
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  uid uuid := auth.uid();
  ref_lesson text;
begin
  if uid is null then raise exception 'not authenticated'; end if;

  select lesson_id into ref_lesson
    from public.course_phrases
   where course_id = p_course_id and phrase_id = p_phrase_id;
  if ref_lesson is null then
    raise exception 'unknown phrase: %/%', p_course_id, p_phrase_id using errcode = 'P0002';
  end if;
  if p_lesson_id is not null and p_lesson_id <> ref_lesson then
    raise exception 'phrase % not in lesson %', p_phrase_id, p_lesson_id using errcode = 'P0001';
  end if;

  insert into public.course_phrase_progress (user_id, course_id, lesson_id, phrase_id, learned, learned_at)
  values (uid, p_course_id, ref_lesson, p_phrase_id, p_learned, case when p_learned then now() else null end)
  on conflict (user_id, course_id, lesson_id, phrase_id) do update set
    learned    = excluded.learned,
    learned_at = case
                   when excluded.learned and course_phrase_progress.learned_at is null then now()
                   when not excluded.learned then null
                   else course_phrase_progress.learned_at
                 end,
    updated_at = now();
end;
$$;

-- submit_course_voice_attempt: append-only. Validates phrase, result enum, score
-- bounds. NO transcript is accepted or stored (privacy).
create or replace function public.submit_course_voice_attempt(
  p_course_id text,
  p_lesson_id text,
  p_phrase_id text,
  p_result    text,
  p_score     int default null
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  uid uuid := auth.uid();
  ref_lesson text;
begin
  if uid is null then raise exception 'not authenticated'; end if;
  if p_result not in ('pass','retry','manual') then
    raise exception 'invalid result: %', p_result;
  end if;
  if p_score is not null and (p_score < 0 or p_score > 100) then
    raise exception 'invalid score: %', p_score;
  end if;

  select lesson_id into ref_lesson
    from public.course_phrases
   where course_id = p_course_id and phrase_id = p_phrase_id;
  if ref_lesson is null then
    raise exception 'unknown phrase: %/%', p_course_id, p_phrase_id using errcode = 'P0002';
  end if;

  insert into public.course_voice_attempts (user_id, course_id, lesson_id, phrase_id, result, score)
  values (uid, p_course_id, ref_lesson, p_phrase_id, p_result, case when p_result = 'manual' then null else p_score end);
end;
$$;

-- submit_course_quiz_attempt: append-only. Server computes passed (>=70%).
create or replace function public.submit_course_quiz_attempt(
  p_course_id text,
  p_lesson_id text,
  p_correct   int,
  p_total     int
)
returns table(score int, total int, passed boolean)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  uid uuid := auth.uid();
  lesson_exists boolean;
  did_pass boolean;
begin
  if uid is null then raise exception 'not authenticated'; end if;
  if p_total is null or p_total <= 0 then raise exception 'invalid total: %', p_total; end if;
  if p_correct is null or p_correct < 0 or p_correct > p_total then
    raise exception 'invalid correct: % of %', p_correct, p_total;
  end if;

  select exists(
    select 1 from public.course_phrases where course_id = p_course_id and lesson_id = p_lesson_id
  ) into lesson_exists;
  if not lesson_exists then
    raise exception 'unknown lesson: %/%', p_course_id, p_lesson_id using errcode = 'P0002';
  end if;

  did_pass := round((p_correct::numeric / p_total::numeric) * 100) >= 70;

  insert into public.course_quiz_attempts (user_id, course_id, lesson_id, score, total, passed)
  values (uid, p_course_id, p_lesson_id, p_correct, p_total, did_pass);

  submit_course_quiz_attempt.score  := p_correct;
  submit_course_quiz_attempt.total  := p_total;
  submit_course_quiz_attempt.passed := did_pass;
  return next;
end;
$$;

-- mark_course_lesson_complete: validates lesson; guards completion behind at
-- least one learned phrase in that lesson (light anti-forge). Upserts.
create or replace function public.mark_course_lesson_complete(
  p_course_id text,
  p_lesson_id text,
  p_completed boolean default true
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  uid uuid := auth.uid();
  lesson_exists boolean;
  has_learned boolean;
begin
  if uid is null then raise exception 'not authenticated'; end if;

  select exists(
    select 1 from public.course_phrases where course_id = p_course_id and lesson_id = p_lesson_id
  ) into lesson_exists;
  if not lesson_exists then
    raise exception 'unknown lesson: %/%', p_course_id, p_lesson_id using errcode = 'P0002';
  end if;

  if p_completed then
    select exists(
      select 1 from public.course_phrase_progress
       where user_id = uid and course_id = p_course_id and lesson_id = p_lesson_id and learned = true
    ) into has_learned;
    if not has_learned then
      raise exception 'cannot complete lesson with no learned phrases' using errcode = 'P0001';
    end if;
  end if;

  insert into public.course_lesson_progress (user_id, course_id, lesson_id, completed, completed_at)
  values (uid, p_course_id, p_lesson_id, p_completed, case when p_completed then now() else null end)
  on conflict (user_id, course_id, lesson_id) do update set
    completed    = excluded.completed,
    completed_at = case
                     when excluded.completed and course_lesson_progress.completed_at is null then now()
                     when not excluded.completed then null
                     else course_lesson_progress.completed_at
                   end,
    updated_at = now();
end;
$$;

